const truncateLabel = (str: string, maxLen = 16) => {
  if (!str) return '';
  return str.length > maxLen ? str.slice(0, maxLen - 1) + '…' : str;
};

const D3GroupedBarChart: React.FC<{ data: ConnectorAuditSummary[] }> = ({ data }) => {
  const chartRef = useRef<SVGSVGElement>(null);
  const containerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!data || data.length === 0 || !chartRef.current || !containerRef.current) return;

    // Clear previous charts
    d3.select(chartRef.current).selectAll('*').remove();

    const margin = { top: 25, right: 25, bottom: 95, left: 55 };
    const containerWidth = containerRef.current.clientWidth;
    const width = containerWidth - margin.left - margin.right;
    const height = 360 - margin.top - margin.bottom;

    const svg = d3
      .select(chartRef.current)
      .attr('width', containerWidth)
      .attr('height', height + margin.top + margin.bottom)
      .style('overflow', 'hidden')
      .append('g')
      .attr('transform', `translate(${margin.left},${margin.top})`);

    const subgroups = ['nulls', 'duplicates', 'typeMismatches'];
    const groups = data.map((d) => d.connectorName);

    // X scale
    const x = d3
      .scaleBand()
      .domain(groups)
      .range([0, width])
      .padding(0.28);

    // X Axis group with smart truncated labels matching connector names cleanly
    svg
      .append('g')
      .attr('transform', `translate(0,${height})`)
      .call(
        d3
          .axisBottom(x)
          .tickSize(0)
          .tickFormat((d) => truncateLabel(d as string, 16))
      )
      .selectAll('text')
      .attr('transform', 'translate(-8,6)rotate(-35)')
      .style('text-anchor', 'end')
      .style('font-size', '10.5px')
      .style('font-weight', '600')
      .style('fill', '#475569');

    // X Subgroup scale
    const xSubgroup = d3
      .scaleBand()
      .domain(subgroups)
      .range([0, x.bandwidth()])
      .padding(0.08);

    // Y scale
    const maxVal = d3.max(data, (d: any) => Math.max(d.totalNulls, d.totalDuplicates, d.totalTypeMismatches)) || 0;
    const y = d3
      .scaleLinear()
      .domain([0, maxVal * 1.15])
      .range([height, 0]);

    // Y Axis group with crisp slate-700 text
    svg
      .append('g')
      .call(d3.axisLeft(y).ticks(5).tickFormat((d) => d3.format('.2s')(d as number)))
      .selectAll('text')
      .style('font-size', '10.5px')
      .style('font-weight', '600')
      .style('fill', '#475569');

    // Style domains & axis ticks
    svg.selectAll('.domain').style('stroke', '#cbd5e1');
    svg.selectAll('.tick line').style('stroke', '#cbd5e1');

    // Light theme soft gridlines
    svg
      .append('g')
      .attr('class', 'grid')
      .call(
        d3
          .axisLeft(y)
          .ticks(5)
          .tickSize(-width)
          .tickFormat(() => '')
      )
      .selectAll('line')
      .style('stroke', '#e2e8f0')
      .style('stroke-opacity', '0.8')
      .style('stroke-dasharray', '3,3');

    // High-contrast vivid colors for Light Mode: Sky Blue (#0284c7), Amber (#d97706), Rose (#e11d48)
    const color = d3
      .scaleOrdinal()
      .domain(subgroups)
      .range(['#0284c7', '#d97706', '#e11d48']);

    // Map/Process dataset for subgroups
    const processedData = data.map((d) => ({
      connectorName: d.connectorName,
      nulls: d.totalNulls,
      duplicates: d.totalDuplicates,
      typeMismatches: d.totalTypeMismatches,
    }));

    // Sleek dark tooltip on light mode
    const tooltip = d3
      .select(containerRef.current)
      .append('div')
      .style('opacity', 0)
      .attr(
        'class',
        'absolute bg-slate-900 text-white border border-slate-800 text-xs rounded-xl px-3.5 py-2.5 pointer-events-none z-30 shadow-xl font-mono leading-relaxed'
      );

    svg
      .append('g')
      .selectAll('g')
      .data(processedData)
      .enter()
      .append('g')
      .attr('transform', (d: any) => `translate(${x(d.connectorName) || 0},0)`)
      .selectAll('rect')
      .data(function (d: any) {
        return subgroups.map((key) => ({ key, value: d[key as keyof typeof d] as number, name: d.connectorName }));
      })
      .enter()
      .append('rect')
      .attr('x', (d) => xSubgroup(d.key)!)
      .attr('y', () => y(0))
      .attr('width', xSubgroup.bandwidth())
      .attr('height', () => height - y(0))
      .attr('fill', (d) => color(d.key) as string)
      .attr('rx', 3)
      .style('cursor', 'pointer')
      .on('mouseover', function (event, d) {
        d3.select(this).style('opacity', 0.85);
        tooltip.transition().duration(150).style('opacity', 1);

        const labelStr = d.key === 'typeMismatches' ? 'Type Mismatches' : d.key.charAt(0).toUpperCase() + d.key.slice(1);
        tooltip
          .html(
            `
            <div class="font-sans font-bold text-white mb-1 border-b border-slate-800 pb-1">${d.name}</div>
            <div class="flex items-center gap-2">
              <span class="w-2.5 h-2.5 rounded-full" style="background-color: ${color(d.key)}"></span>
              <span>${labelStr}: <strong class="text-white text-sm">${d.value.toLocaleString()}</strong></span>
            </div>
          `
          )
          .style('left', event.clientX - containerRef.current!.getBoundingClientRect().left + 15 + 'px')
          .style('top', event.clientY - containerRef.current!.getBoundingClientRect().top - 20 + 'px');
      })
      .on('mousemove', function (event) {
        tooltip
          .style('left', event.clientX - containerRef.current!.getBoundingClientRect().left + 15 + 'px')
          .style('top', event.clientY - containerRef.current!.getBoundingClientRect().top - 20 + 'px');
      })
      .on('mouseleave', function () {
        d3.select(this).style('opacity', 1);
        tooltip.transition().duration(200).style('opacity', 0);
      })
      .transition()
      .duration(750)
      .attr('y', (d) => y(d.value))
      .attr('height', (d) => height - y(d.value));

    // Cleanup tooltip
    return () => {
      tooltip.remove();
    };
  }, [data]);

  return (
    <div ref={containerRef} className="w-full relative overflow-hidden pb-1">
      <svg ref={chartRef} className="max-w-full overflow-hidden"></svg>
    </div>
  );
};

const D3DonutChart: React.FC<{ data: ConnectorAuditSummary[] }> = ({ data }) => {
  const chartRef = useRef<SVGSVGElement>(null);
  const containerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!data || data.length === 0 || !chartRef.current || !containerRef.current) return;

    d3.select(chartRef.current).selectAll('*').remove();

    const containerWidth = containerRef.current.clientWidth;
    const height = 250;
    const margin = 10;
    const radius = Math.min(containerWidth, height) / 2 - margin;

    const totalNulls = d3.sum(data, (d: any) => d.totalNulls);
    const totalDuplicates = d3.sum(data, (d: any) => d.totalDuplicates);
    const totalMismatches = d3.sum(data, (d: any) => d.totalTypeMismatches);
    const totalSum = totalNulls + totalDuplicates + totalMismatches;

    const pieData = [
      { key: 'Null Values', value: totalNulls, color: '#0284c7' },
      { key: 'Duplicate Records', value: totalDuplicates, color: '#d97706' },
      { key: 'Type Mismatches', value: totalMismatches, color: '#e11d48' },
    ];

    const svg = d3
      .select(chartRef.current)
      .attr('width', containerWidth)
      .attr('height', height)
      .style('overflow', 'hidden')
      .append('g')
      .attr('transform', `translate(${containerWidth / 2},${height / 2})`);

    const pie = d3
      .pie<any>()
      .value((d) => d.value)
      .sort(null);
    const arc = d3
      .arc<any>()
      .innerRadius(radius * 0.6)
      .outerRadius(radius * 0.88)
      .cornerRadius(5)
      .padAngle(0.04);
    const arcHover = d3
      .arc<any>()
      .innerRadius(radius * 0.6)
      .outerRadius(radius * 0.94)
      .cornerRadius(5)
      .padAngle(0.04);

    const tooltip = d3
      .select(containerRef.current)
      .append('div')
      .style('opacity', 0)
      .attr(
        'class',
        'absolute bg-slate-900 text-white border border-slate-800 text-xs rounded-xl px-3.5 py-2.5 pointer-events-none z-30 shadow-xl font-mono text-center'
      );

    svg
      .selectAll('allSlices')
      .data(pie(pieData))
      .enter()
      .append('path')
      .attr('d', arc as any)
      .attr('fill', (d) => d.data.color)
      .attr('stroke', '#ffffff')
      .style('stroke-width', '3px')
      .style('cursor', 'pointer')
      .on('mouseover', function (event, d) {
        d3.select(this).transition().duration(150).attr('d', arcHover as any);

        tooltip.transition().duration(150).style('opacity', 1);
        const pct = ((d.data.value / (totalSum || 1)) * 100).toFixed(1);
        tooltip
          .html(
            `
            <div class="font-sans font-bold text-white mb-0.5">${d.data.key}</div>
            <div class="text-base font-extrabold" style="color: ${d.data.color}">${d.data.value.toLocaleString()}</div>
            <div class="text-[10px] text-slate-400 mt-0.5">${pct}% of overall faults</div>
          `
          )
          .style('left', event.clientX - containerRef.current!.getBoundingClientRect().left + 15 + 'px')
          .style('top', event.clientY - containerRef.current!.getBoundingClientRect().top - 20 + 'px');
      })
      .on('mousemove', function (event) {
        tooltip
          .style('left', event.clientX - containerRef.current!.getBoundingClientRect().left + 15 + 'px')
          .style('top', event.clientY - containerRef.current!.getBoundingClientRect().top - 20 + 'px');
      })
      .on('mouseleave', function () {
        d3.select(this).transition().duration(200).attr('d', arc as any);
        tooltip.transition().duration(200).style('opacity', 0);
      });

    // Central metrics overview inside donut (Light Mode: Slate-900 text)
    svg
      .append('text')
      .attr('text-anchor', 'middle')
      .attr('y', -4)
      .style('font-size', '24px')
      .style('font-weight', '900')
      .style('font-family', 'JetBrains Mono, ui-monospace, monospace')
      .style('fill', '#0f172a')
      .text(d3.format('.2s')(totalSum));

    svg
      .append('text')
      .attr('text-anchor', 'middle')
      .attr('y', 16)
      .style('font-size', '10px')
      .style('font-weight', '800')
      .style('letter-spacing', '0.05em')
      .style('fill', '#64748b')
      .text('TOTAL FAULTS');

    return () => {
      tooltip.remove();
    };
  }, [data]);

  return (
    <div ref={containerRef} className="w-full relative overflow-hidden">
      <svg ref={chartRef} className="max-w-full overflow-hidden"></svg>
    </div>
  );
};
